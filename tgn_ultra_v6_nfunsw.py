class Memory(nn.Module):
    def __init__(self, n_nodes, memory_dimension, input_dimension,
                 message_dimension=None, device='cpu'):
        super().__init__()
        self.n_nodes = n_nodes; self.memory_dimension = memory_dimension
        self.device  = device
        self.memory     = nn.Parameter(torch.zeros(n_nodes, memory_dimension).to(device), requires_grad=False)
        self.last_update= nn.Parameter(torch.zeros(n_nodes).to(device), requires_grad=False)
        self.messages   = defaultdict(list)

    def store_raw_messages(self, nodes, nid2msgs):
        for n in nodes: self.messages[n].extend(nid2msgs[n])

    def get_memory(self, ids):   return self.memory[ids,:]
    def set_memory(self, ids, v): self.memory[ids,:] = v
    def get_last_update(self, ids): return self.last_update[ids]

    def backup_memory(self):
        clone = {k:[(x[0].clone(),x[1].clone()) for x in v] for k,v in self.messages.items()}
        return self.memory.data.clone(), self.last_update.data.clone(), clone

    def restore_memory(self, bk):
        self.memory.data, self.last_update.data = bk[0].clone(), bk[1].clone()
        self.messages = defaultdict(list)
        for k,v in bk[2].items(): self.messages[k] = [(x[0].clone(),x[1].clone()) for x in v]

    def detach_memory(self):
        self.memory.detach_()
        for k,v in self.messages.items():
            self.messages[k] = [(m[0].detach(), m[1]) for m in v]

    def clear_messages(self, nodes):
        for n in nodes: self.messages[n] = []


