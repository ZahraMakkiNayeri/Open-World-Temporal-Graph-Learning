    def compute_embeddings(self, src, dst, neg, ts, eidx, n_nbr=None):
        n_nbr = n_nbr or self.n_neighbors
        n     = len(src)
        nodes = np.concatenate([src, dst, neg])
        tss   = np.concatenate([ts, ts, ts])
        memory = None; time_diffs = None

        if self.use_memory:
            if self.memory_update_at_start:
                memory, last_update = self._get_updated_memory(
                    list(range(self.n_nodes)), self.memory.messages)
            else:
                memory      = self.memory.get_memory(list(range(self.n_nodes)))
                last_update = self.memory.last_update

            def td(nodes_arr, m, s):
                d = torch.LongTensor(ts).to(self.device) - last_update[nodes_arr].long()
                return (d.float() - m) / s

            time_diffs = torch.cat([
                td(src, self.mean_ts_src, self.std_ts_src),
                td(dst, self.mean_ts_dst, self.std_ts_dst),
                td(neg, self.mean_ts_dst, self.std_ts_dst)])

        emb = self.embedding.compute_embedding(memory, nodes, tss,
                                                self.n_layers, n_nbr, time_diffs)
        src_e = emb[:n]; dst_e = emb[n:2*n]; neg_e = emb[2*n:]

        if self.use_memory:
            if self.memory_update_at_start:
                self._update_memory(src, self.memory.messages)
                self._update_memory(dst, self.memory.messages)
            else:
                pos = np.concatenate([src, dst])
                self._update_memory(pos, self.memory.messages)

            self.memory.clear_messages(src); self.memory.clear_messages(dst)
            rm_src, rm_dst = self._get_raw_messages(src, src_e, dst, dst_e, ts, eidx)

            # Project to message_dim BEFORE storing
            rm_src_proj = {
                n: [(self.message_fn.compute_message(m[0]), m[1]) for m in msgs]
                for n, msgs in rm_src.items()
            }
            rm_dst_proj = {
                n: [(self.message_fn.compute_message(m[0]), m[1]) for m in msgs]
                for n, msgs in rm_dst.items()
            }
            self.memory.store_raw_messages(src, rm_src_proj)   # now dim=100 ✓
            self.memory.store_raw_messages(dst, rm_dst_proj)   # now dim=100 ✓
            #self.memory.store_raw_messages(src, rm_src)
            #self.memory.store_raw_messages(dst, rm_dst)

        return src_e, dst_e, neg_e

    def forward(self, src, dst, neg, ts, eidx, motif_pos, motif_neg, n_nbr=None):
        """
        Returns:
          pos_score, neg_score, cat_logits, joint_repr, ultra_pos_score
        """
        src_e, dst_e, neg_e = self.compute_embeddings(src, dst, neg, ts, eidx, n_nbr)

        # TGN affinity (used in BCE loss)
        pos_tgn = self.affinity(src_e, dst_e).sigmoid().squeeze(-1)
        neg_tgn = self.affinity(src_e, neg_e).sigmoid().squeeze(-1)

        # ULTRA structural link score + category logits
        motif_t_pos = torch.FloatTensor(motif_pos).to(self.device)
        motif_t_neg = torch.FloatTensor(motif_neg).to(self.device)

        ultra_pos, cat_logits, joint_repr = self.ultra(src_e, dst_e, motif_t_pos)
        ultra_neg, _,          _          = self.ultra(src_e, neg_e, motif_t_neg)

        # Ensemble: blend TGN and ULTRA scores
        pos_score = 0.5*(pos_tgn + ultra_pos.sigmoid())
        neg_score = 0.5*(neg_tgn + ultra_neg.sigmoid())

        return pos_score, neg_score, cat_logits, joint_repr, ultra_pos

