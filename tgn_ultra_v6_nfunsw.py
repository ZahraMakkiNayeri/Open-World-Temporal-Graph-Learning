def _as_zd_set(zero_day_category):
    """Accept a single category name (str) or several (list/tuple/set)."""
    if zero_day_category is None:
        return set()
    if isinstance(zero_day_category, (list, tuple, set)):
        return set(zero_day_category)
    return {zero_day_category}


def preprocess(df, zero_day_category=None):
    """
    Converts raw CSV to temporal-edge-list format.
    `zero_day_category` may be a single category name OR a list of names.
    ALL held-out categories get the SAME label = num_known (one beyond the
    known classes), collapsing every unseen type into one 'unknown' class.
    """
    df = df.copy()
    df['SourceIP'] = df['SourceIP'].astype(str)
    df['TargetIP']  = df['TargetIP'].astype(str)

    zd_set = _as_zd_set(zero_day_category)

    # Encode known categories (exclude ALL held-out categories from encoder fitting)
    known_mask = ~df['Category'].isin(zd_set) if zd_set else pd.Series([True]*len(df))
    attack_enc = LabelEncoder()
    attack_enc.fit(df.loc[known_mask, 'Category'])
    num_known  = len(attack_enc.classes_)

    proto_enc  = LabelEncoder()
    port_enc   = LabelEncoder()
    proto_enc.fit(df['Proto'].astype(str))
    port_enc.fit(df['Port'].astype(str))

    df['Proto_enc']    = proto_enc.transform(df['Proto'].astype(str))
    df['Port_enc']     = port_enc.transform(df['Port'].astype(str))
    df['Category_enc'] = df['Category'].apply(
        lambda c: num_known if c in zd_set        # ← any held-out type -> unknown label
                  else attack_enc.transform([c])[0])

    df['src_enc'], _ = pd.factorize(df['SourceIP'])
    df['dst_enc'], _ = pd.factorize(df['TargetIP'])

    records, feats = [], []
    for _, row in df.iterrows():
        records.append({
            'u'    : row['src_enc'],
            'i'    : row['dst_enc'],
            'ts'   : row['DetectTime'].timestamp(),
            'label': row['Category_enc'],
            'idx'  : _,
        })
        feats.append([row['FlowCount'], row['Port_enc'], row['Proto_enc']])

    processed = pd.DataFrame(records)
    processed['original_date'] = pd.to_datetime(processed['ts'], unit='s')
    category_mapping = {i: lbl for i, lbl in enumerate(attack_enc.classes_)}
    category_mapping[num_known] = ("|".join(sorted(zd_set)) if zd_set else None)  # zero-day label(s)
    return processed, np.array(feats, dtype=np.float32), category_mapping, num_known


def reindex(df):
    new_df = df.copy()
    upper_u     = int(df.u.max()) + 1
    new_df['i'] = df.i + upper_u
    new_df['u'] = df.u + 1
    new_df['i'] = new_df['i'] + 1
    new_df['idx'] = np.arange(len(df)) + 1   # +1: edge index 0 is the zero-pad row
    return new_df


def run_pipeline(df, zero_day_category=None, node_feat_dim=172):
    processed, feat, cat_map, num_known = preprocess(df, zero_day_category)
    new_df = reindex(processed)
    empty  = np.zeros(feat.shape[1])[np.newaxis, :]
    feat   = np.vstack([empty, feat])
    max_idx= max(new_df.u.max(), new_df.i.max())
    node_features = np.zeros((max_idx + 1, node_feat_dim), dtype=np.float32)
    return new_df, feat, node_features, cat_map, num_known


