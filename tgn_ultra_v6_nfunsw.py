class EarlyStopMonitor:
    def __init__(self, max_round=5, higher_better=True, tolerance=1e-6):
        self.max_round = max_round; self.num_round = 0
        self.epoch_count = 0; self.best_epoch = 0
        self.last_best = None; self.higher_better = higher_better; self.tol = tolerance
    def early_stop_check(self, v):
        if not self.higher_better: v = -v
        if self.last_best is None: self.last_best = v
        elif (v - self.last_best) / (abs(self.last_best)+1e-12) > self.tol:
            self.last_best = v; self.num_round = 0; self.best_epoch = self.epoch_count
        else: self.num_round += 1
        self.epoch_count += 1
        return self.num_round >= self.max_round

def compute_time_statistics(srcs, dsts, tss):
    ls, ld = defaultdict(int), defaultdict(int)
    ds, dd = [], []
    for s, d, t in zip(srcs, dsts, tss):
        ds.append(t - ls[s]); dd.append(t - ld[d])
        ls[s] = t; ld[d] = t
    return float(np.mean(ds)), float(np.std(ds)+1e-9), float(np.mean(dd)), float(np.std(dd)+1e-9)

