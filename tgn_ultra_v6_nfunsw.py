"""## Section 5 – Fourier Series Message Aggregator

**Algorithm** – for node $v$ with messages $\{\mathbf{m}_j\}$ at times $\{t_j\}$:

1. Normalise $\tau_j = 2\pi(t_j - t_{\min})/(t_{\max}-t_{\min})$
2. DC: $a_0 = \frac{1}{T}\sum_j \mathbf{m}_j$
3. Harmonics: $a_k = \frac{1}{T}\sum_j \mathbf{m}_j\cos(k\tau_j)$, $b_k = \frac{1}{T}\sum_j \mathbf{m}_j\sin(k\tau_j)$
4. Reconstruct at $\tau_T$: $\tilde{\mathbf{m}} = \frac{a_0}{2} + \sum_{k=1}^K[a_k\cos(k\tau_T)+b_k\sin(k\tau_T)]$
5. Project via learned linear → final aggregated message

"""

class MessageAggregator(nn.Module):
    def __init__(self, device):
        super().__init__(); self.device = device
    def aggregate(self, node_ids, messages): raise NotImplementedError


class FourierSeriesMessageAggregator(MessageAggregator):
    """
    Temporal message aggregation via truncated Fourier series.
    Captures periodic attack traffic patterns (daily scan cycles,
    burst DDoS rhythms) that flat mean/last aggregators miss.
    """
    def __init__(self, device, message_dim, n_harmonics=8):
        super().__init__(device)
        self.message_dim = message_dim
        self.n_harmonics = n_harmonics
        fourier_out = message_dim * (1 + 2 * n_harmonics)
        self.proj = nn.Linear(fourier_out, message_dim, bias=True)
        nn.init.xavier_normal_(self.proj.weight)

    def aggregate(self, node_ids, messages):
        unique_ids = np.unique(node_ids)
        to_update, agg_msgs, agg_ts = [], [], []

        for nid in unique_ids:
            seq = messages.get(nid, [])
            if not seq: continue
            seq      = sorted(seq, key=lambda x: x[1])
            msgs     = torch.stack([m[0] for m in seq]).to(self.device)  # [T,D]
            raw_ts   = torch.tensor([m[1] for m in seq], dtype=torch.float32, device=self.device)
            T        = msgs.size(0)

            # Normalise to [0, 2π]
            t_min, t_max = raw_ts.min(), raw_ts.max()
            tau = 2*math.pi*(raw_ts-t_min)/(t_max-t_min+1e-9)

            # DC
            a0 = msgs.mean(0)
            parts = [a0 / 2.0]

            # Harmonics
            sin_parts = []
            for k in range(1, self.n_harmonics+1):
                kt  = k * tau
                ak  = (msgs * torch.cos(kt).unsqueeze(1)).mean(0)
                bk  = (msgs * torch.sin(kt).unsqueeze(1)).mean(0)
                parts.append(ak); sin_parts.append(bk)

            # Reconstruct at τ_T
            tau_T = tau[-1].item()
            recon = [parts[0]]
            for k in range(1, self.n_harmonics+1):
                recon.append(parts[k] * math.cos(k*tau_T))
                recon.append(sin_parts[k-1] * math.sin(k*tau_T))

            fvec    = torch.cat(recon, dim=0)
            agg_msg = self.proj(fvec.unsqueeze(0)).squeeze(0)

            to_update.append(nid); agg_msgs.append(agg_msg)
            agg_ts.append(raw_ts[-1])

        if to_update:
            return to_update, torch.stack(agg_msgs), torch.stack(agg_ts)
        return [], (torch.empty((0, self.message_dim), device=self.device),
                    torch.empty((0,), device=self.device))


class LastMessageAggregator(MessageAggregator):
    def aggregate(self, node_ids, messages):
        to_update, agg_msgs, agg_ts = [], [], []
        for nid in np.unique(node_ids):
            seq = messages.get(nid, [])
            if not seq: continue
            seq = sorted(seq, key=lambda x: x[1])
            to_update.append(nid)
            agg_msgs.append(seq[-1][0].to(self.device))
            agg_ts.append(torch.tensor(seq[-1][1], device=self.device))
        if to_update:
            return to_update, torch.stack(agg_msgs), torch.stack(agg_ts)
        d = list(messages.values())[0][0][0].shape[0]
        return [], torch.empty((0,d),device=self.device), torch.empty((0,),device=self.device)


