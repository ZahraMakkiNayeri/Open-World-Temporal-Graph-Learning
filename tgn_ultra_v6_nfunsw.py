"""### 17.2 OOD-signal ablation + α blend sweep (no retrain)

Reuses the already-trained `model` via its stored validation/test scores (`val_result`, `te_result`). Energy-only corresponds to α=1, prototype-distance-only to α=0, the combined detector to α=0.5.
"""

def _zd_at_alpha(vr, tr, alpha):
    """Recalibrate the combined OOD score at a given alpha and return test (F1, AUC)."""
    ve, vd = vr['energies'], vr['proto_dists']
    te_, td = tr['energies'], tr['proto_dists']
    kn = ~vr['zd_true']
    em, es = ve[kn].mean(), ve[kn].std()+1e-9
    dm, ds = vd[kn].mean(), vd[kn].std()+1e-9
    sc = lambda e,d: alpha*((e-em)/es) + (1-alpha)*((d-dm)/ds)
    vs, ts = sc(ve,vd), sc(te_,td)
    best_f1, best_t = 0.0, vs.min()
    for t in np.linspace(vs.min(), vs.max(), 200):          # tune threshold on val
        f = f1_score(vr['zd_true'].astype(int), (vs>t).astype(int), zero_division=0)
        if f > best_f1: best_f1, best_t = f, t
    zt = tr['zd_true']
    f1 = f1_score(zt.astype(int), (ts>best_t).astype(int), zero_division=0)
    a  = roc_auc_score(zt.astype(int), ts) if (zt.any() and (~zt).any()) else 0.0
    return f1, a

