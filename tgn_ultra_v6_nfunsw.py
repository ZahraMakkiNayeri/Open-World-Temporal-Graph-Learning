def evaluate(model, motif_desc, neg_sampler, data, n_nbr,
             num_known_cats, batch_size=256, return_repr=False,
             link_threshold=None):
    """
    Returns a dict with standard link-prediction metrics AND zero-day metrics.

    link_threshold : if provided, use this fixed decision threshold for the
                     link F1/TPR/FPR. Pass the VALIDATION threshold at test
                     time so the threshold is NOT fit on the test labels.

    Ranking metrics (MRR / Hits@k) rank each positive against the ENTIRE pool
    of sampled negatives in this split, not just its single paired negative,
    so Hits@k for k>1 are meaningful.
    """
    neg_sampler.reset_random_state()

    all_pos_scores, all_neg_scores = [], []
    all_ap, all_auc = [], []
    all_cat_preds, all_cat_true = [], []
    all_energies, all_proto_dists, all_zd_true = [], [], []
    all_msp = []
    all_joint = [] if return_repr else None

    hits = {k: [] for k in [1, 3, 5, 10, 50, 100]}

    model.eval()
    with torch.no_grad():
        N = len(data.sources)
        for k in range(math.ceil(N / batch_size)):
            s = k * batch_size; e = min(N, s + batch_size)
            src  = data.sources[s:e];    dst  = data.destinations[s:e]
            ts   = data.timestamps[s:e]; eidx = data.edge_idxs[s:e]
            lbls = data.labels[s:e]
            B    = len(src)
            _, neg = neg_sampler.sample(B)

            mot_pos = motif_desc.compute_batch(src, dst, ts, lbls)
            mot_neg = motif_desc.compute_batch(src, neg, ts, lbls)

            pos_p, neg_p, cat_logits, joint, ultra_pos = model(
                src, dst, neg, ts, eidx, mot_pos, mot_neg, n_nbr)

            ps = pos_p.cpu().numpy(); ns = neg_p.cpu().numpy()
            all_pos_scores.extend(ps.tolist()); all_neg_scores.extend(ns.tolist())

            true_lk = np.concatenate([np.ones(B), np.zeros(B)])
            pred_sc = np.concatenate([ps, ns])
            try:
                all_ap.append(average_precision_score(true_lk, pred_sc))
                all_auc.append(roc_auc_score(true_lk, pred_sc))
            except: pass

            # Category classification (known classes only)
            known_mask = lbls < num_known_cats
            if known_mask.any():
                known_logits = cat_logits[known_mask]
                all_cat_true.extend(lbls[known_mask].tolist())
                preds = torch.argmax(known_logits, 1).cpu().numpy()
                all_cat_preds.extend(preds.tolist())

            # OOD / Zero-Day signals
            E      = ZeroDayDetector.energy_score(cat_logits)
            _sm    = torch.softmax(cat_logits, dim=1)
            all_msp.extend((1.0 - _sm.max(dim=1).values).cpu().numpy().tolist())
            pd_mat = model.ultra.compute_prototype_distances(joint).cpu().numpy()
            d_min  = ZeroDayDetector.min_proto_dist(pd_mat)
            all_energies.extend(E.tolist())
            all_proto_dists.extend(d_min.tolist())
            all_zd_true.extend((lbls == num_known_cats).tolist())

            if return_repr: all_joint.append(joint.cpu().numpy())

    # ── Ranking metrics: rank each positive against the WHOLE negative pool ──
    ps_arr = np.array(all_pos_scores); ns_arr = np.array(all_neg_scores)
    all_mrr = []
    if ps_arr.size and ns_arr.size:
        ns_sorted = np.sort(ns_arr)
        n_neg     = ns_arr.size
        for p in ps_arr:
            # number of negatives scoring strictly higher than this positive
            higher = n_neg - np.searchsorted(ns_sorted, p, side='right')
            rank   = higher + 1
            all_mrr.append(1.0 / rank)
            for kk in hits: hits[kk].append(rank <= kk)

    # ── Link decision metrics ─────────────────────────────────
    all_scores      = np.concatenate([ps_arr, ns_arr]) if ps_arr.size else np.array([])
    all_link_labels = np.concatenate([np.ones(ps_arr.size), np.zeros(ns_arr.size)])
    if link_threshold is None:
        best_t, _ = find_best_threshold(all_link_labels, all_scores)
    else:
        best_t = link_threshold
    y_pred        = (all_scores >= best_t).astype(int)
    tn, fp, fn, tp = confusion_matrix(all_link_labels, y_pred, labels=[0, 1]).ravel()

    cat_acc = (np.array(all_cat_preds) == np.array(all_cat_true)).mean() if all_cat_true else 0.0
    zd_true = np.array(all_zd_true, dtype=bool)

    result = dict(
        ap          = float(np.mean(all_ap))  if all_ap  else 0.0,
        auc         = float(np.mean(all_auc)) if all_auc else 0.0,
        mrr         = float(np.mean(all_mrr)) if all_mrr else 0.0,
        f1          = float(f1_score(all_link_labels, y_pred, zero_division=0)),
        tpr         = float(tp / (tp + fn + 1e-9)),
        fpr         = float(fp / (fp + tn + 1e-9)),
        cat_acc     = float(cat_acc),
        threshold   = float(best_t),
        hits        = {k: (float(np.mean(v)) if v else 0.0) for k, v in hits.items()},
        energies    = np.array(all_energies),
        msp         = np.array(all_msp),
        proto_dists = np.array(all_proto_dists),
        zd_true     = zd_true,
        joint       = (np.concatenate(all_joint, 0) if return_repr else None),
    )
    return result


def find_best_threshold(y_true, y_scores):
    best_f1, best_t = 0.0, 0.5
    for t in np.linspace(0.01, 0.99, 99):
        p = (y_scores >= t).astype(int)
        f = f1_score(y_true, p, zero_division=0)
        if f > best_f1: best_f1, best_t = f, t
    return best_t, best_f1

