"""### 18.4b Per-class score normalisation (fix for the DDoS AUC<0.5 failure)

The combined detector standardises energy/distance against *all* known
samples. Classes whose structure naturally yields small prototype distance
(e.g. DDoS overlapping Recon) then look in-distribution and can score *below*
chance. The per-class detector standardises each test sample against the
validation statistics of the known class it most resembles (its predicted
class), so 'anomalous' means anomalous *relative to its nearest known class*.

Run with `RUN_TDSC_SUITE=True` to retrain per held-out category and compare
global vs per-class normalisation across the full LOCO sweep.
"""

class PerClassZeroDayDetector:
    """Standardise the energy+distance OOD signal within each predicted known class."""
    def __init__(self, alpha=0.5): self.alpha=alpha
    def fit(self, logits, energy, proto, known_mask, num_known, fpr=0.01):
        pred=logits.argmax(1); self.K=num_known; self.stats={}
        ge=(energy[known_mask].mean(), energy[known_mask].std()+1e-9)
        gd=(proto[known_mask].mean(),  proto[known_mask].std()+1e-9)
        for c in range(num_known):
            m=known_mask & (pred==c)
            if m.sum()>=5:
                self.stats[c]=(energy[m].mean(),energy[m].std()+1e-9,
                               proto[m].mean(), proto[m].std()+1e-9)
            else:
                self.stats[c]=(ge[0],ge[1],gd[0],gd[1])
        s=self.score(logits,energy,proto)
        self.thr=np.quantile(s[known_mask],1-fpr)
        return self
    def score(self, logits, energy, proto):
        pred=logits.argmax(1); out=np.zeros(len(pred))
        for c,(em,es,dm,ds) in self.stats.items():
            m=pred==c
            out[m]=self.alpha*((energy[m]-em)/es)+(1-self.alpha)*((proto[m]-dm)/ds)
        return out
    def predict(self, logits, energy, proto): return self.score(logits,energy,proto)>self.thr

