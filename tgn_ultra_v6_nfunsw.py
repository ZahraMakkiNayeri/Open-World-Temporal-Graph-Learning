class TimeEncode(nn.Module):
    def __init__(self, dimension):
        super().__init__()
        self.dimension = dimension
        self.w = nn.Linear(1, dimension)
        self.w.weight = nn.Parameter(
            (torch.from_numpy(1/10**np.linspace(0,9,dimension))).float().reshape(dimension,-1))
        self.w.bias = nn.Parameter(torch.zeros(dimension).float())
    def forward(self, t):
        return torch.cos(self.w(t.unsqueeze(-1)))


class TemporalAttentionLayer(nn.Module):
    def __init__(self, n_node_feat, n_nbr_feat, n_edge_feat, time_dim,
                 out_dim, n_head=2, dropout=0.1):
        super().__init__()
        self.q_dim = n_node_feat + time_dim
        self.k_dim = n_nbr_feat  + time_dim + n_edge_feat
        self.mha   = nn.MultiheadAttention(embed_dim=self.q_dim, kdim=self.k_dim,
                                            vdim=self.k_dim, num_heads=n_head,
                                            dropout=dropout)
        self.merger = MergeLayer(self.q_dim, n_node_feat, n_node_feat, out_dim)

    def forward(self, src_feat, src_t_feat, nbr_feat, nbr_t_feat,
                edge_feat, pad_mask):
        q = torch.cat([src_feat.unsqueeze(1), src_t_feat], 2).permute(1,0,2)
        k = torch.cat([nbr_feat, edge_feat, nbr_t_feat], 2).permute(1,0,2)
        inv_mask = pad_mask.all(1, keepdim=True)
        pad_mask[inv_mask.squeeze(),:] = False
        out, _ = self.mha(q, k, k, key_padding_mask=pad_mask)
        return self.merger(out.squeeze(0), src_feat), None


class GraphAttentionEmbedding(nn.Module):
    def __init__(self, node_feat, edge_feat, memory, neighbor_finder,
                 time_encoder, n_layers, n_node_feat, n_edge_feat,
                 n_time_feat, emb_dim, device, n_heads=2, dropout=0.1, use_memory=True):
        super().__init__()
        self.node_feat = node_feat; self.edge_feat = edge_feat
        self.memory = memory; self.nf = neighbor_finder
        self.time_enc = time_encoder; self.n_layers = n_layers
        self.n_node_feat = n_node_feat; self.n_edge_feat = n_edge_feat
        self.emb_dim = emb_dim; self.device = device; self.use_memory = use_memory
        self.dropout = nn.Dropout(dropout)
        self.attention_models = nn.ModuleList([
            TemporalAttentionLayer(n_node_feat, n_node_feat, n_edge_feat,
                                   n_time_feat, n_node_feat, n_heads, dropout)
            for _ in range(n_layers)])

    def compute_embedding(self, memory, source_nodes, timestamps, n_layers,
                           n_neighbors=20, time_diffs=None, use_time_proj=True):
        if time_diffs is not None:
            src_t_enc = self.time_enc(time_diffs.unsqueeze(1).float())
        else:
            src_t_enc = self.time_enc(torch.zeros(len(source_nodes),1).float().to(self.device))
        src_feat  = self.node_feat[source_nodes,:]
        if self.use_memory and memory is not None:
            src_feat = src_feat + memory[source_nodes,:]
        if n_layers == 0: return src_feat

        nbrs, eidxs, et = self.nf.get_temporal_neighbor(source_nodes, timestamps, n_neighbors)
        nbrs_flat = nbrs.flatten(); eidxs_flat = eidxs.flatten()
        dt_flat   = (np.tile(timestamps,(n_neighbors,1)).T.flatten() - et.flatten())
        dt_t      = torch.FloatTensor(dt_flat).to(self.device)

        nbr_feat = self.compute_embedding(memory, nbrs_flat,
                                           np.tile(timestamps,(n_neighbors,1)).T.flatten(),
                                           n_layers-1, n_neighbors)
        nbr_feat = nbr_feat.view(len(source_nodes), n_neighbors, -1)

        ef       = self.edge_feat[eidxs_flat,:].view(len(source_nodes), n_neighbors, -1)
        nbr_t    = self.time_enc(dt_t.unsqueeze(1)).view(len(source_nodes), n_neighbors, -1)
        pad_mask = torch.zeros(len(source_nodes), n_neighbors, dtype=torch.bool, device=self.device)

        emb, _   = self.attention_models[n_layers-1](src_feat, src_t_enc, nbr_feat, nbr_t, ef, pad_mask)
        return emb

    def set_neighbor_finder(self, nf): self.nf = nf

