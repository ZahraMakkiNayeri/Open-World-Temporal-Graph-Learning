def get_neighbor_finder(data, uniform, max_node_idx=None):
    # ── FIX: always use the true max across BOTH sources and destinations ──
    true_max = max(int(data.sources.max()), int(data.destinations.max()))
    max_idx  = max(true_max, max_node_idx) if max_node_idx is not None else true_max

    adj = [[] for _ in range(max_idx + 1)]
    for s, d, ei, t in zip(data.sources, data.destinations,
                            data.edge_idxs, data.timestamps):
        adj[int(s)].append((int(d), int(ei), float(t)))
        adj[int(d)].append((int(s), int(ei), float(t)))
    return NeighborFinder(adj, uniform=uniform)


class NeighborFinder:
    def __init__(self, adj_list, uniform=False, seed=None):
        self.node_to_neighbors       = []
        self.node_to_edge_idxs       = []
        self.node_to_edge_timestamps = []
        for nbrs in adj_list:
            sn = sorted(nbrs, key=lambda x: x[2])
            self.node_to_neighbors.append(np.array([x[0] for x in sn]))
            self.node_to_edge_idxs.append(np.array([x[1] for x in sn]))
            self.node_to_edge_timestamps.append(np.array([x[2] for x in sn]))
        self.uniform = uniform
        if seed: self.random_state = np.random.RandomState(seed)

    def find_before(self, src_idx, cut_time):
        i = np.searchsorted(self.node_to_edge_timestamps[src_idx], cut_time)
        return (self.node_to_neighbors[src_idx][:i],
                self.node_to_edge_idxs[src_idx][:i],
                self.node_to_edge_timestamps[src_idx][:i])

    def get_temporal_neighbor(self, source_nodes, timestamps, n_neighbors=20):
        tmp_n = np.zeros((len(source_nodes), n_neighbors), dtype=np.int32)
        tmp_e = np.zeros((len(source_nodes), n_neighbors), dtype=np.int32)
        tmp_t = np.zeros((len(source_nodes), n_neighbors), dtype=np.float32)
        for i, (src, ts) in enumerate(zip(source_nodes, timestamps)):
            src = int(src)
            if src >= len(self.node_to_neighbors): continue
            nbrs, eidxs, t = self.find_before(src, ts)
            if len(nbrs) > 0:
                if self.uniform:
                    idx = np.random.randint(0, len(nbrs), n_neighbors)
                else:
                    idx = np.arange(max(0, len(nbrs)-n_neighbors), len(nbrs))
                    idx = np.pad(idx, (n_neighbors-len(idx), 0), mode='edge')
                tmp_n[i] = nbrs[idx]; tmp_e[i] = eidxs[idx]; tmp_t[i] = t[idx]
        return tmp_n, tmp_e, tmp_t


# ── Random edge sampler ───────────────────────────────────────
class RandEdgeSampler:
    def __init__(self, src_list, dst_list, seed=None):
        self.seed = seed
        self.src_list = np.unique(src_list); self.dst_list = np.unique(dst_list)
        if seed is not None: self.random_state = np.random.RandomState(seed)

    def sample(self, size):
        if self.seed is None:
            si = np.random.randint(0, len(self.src_list), size)
            di = np.random.randint(0, len(self.dst_list), size)
        else:
            si = self.random_state.randint(0, len(self.src_list), size)
            di = self.random_state.randint(0, len(self.dst_list), size)
        return self.src_list[si], self.dst_list[di]

    def reset_random_state(self):
        self.random_state = np.random.RandomState(self.seed)


