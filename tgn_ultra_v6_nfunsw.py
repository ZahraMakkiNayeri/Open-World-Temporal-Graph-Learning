def get_data(graph_df, edge_features, node_features, num_known_cats,
             val_ratio=0.70, test_ratio=0.85,
             different_new_nodes=False, randomize_features=False):
    """
    Split strategy:
    • Training   : 0–70%  of timeline, KNOWN attack types only
    • Validation : 70–85%, known + zero-day (for threshold tuning)
    • Test       : 85–100%, known + zero-day (for final evaluation)
    """
    if randomize_features:
        node_features = np.random.rand(*node_features.shape).astype(np.float32)

    src  = graph_df.u.values.astype(int)
    dst  = graph_df.i.values.astype(int)
    ts   = graph_df.ts.values.astype(float)
    eidx = graph_df.idx.values.astype(int)
    lbl  = graph_df.label.values.astype(int)

    val_ts  = np.quantile(ts, val_ratio)
    test_ts = np.quantile(ts, test_ratio)

    full_data   = Data(src, dst, ts, eidx, lbl)

    is_zd = (lbl == num_known_cats)

    # ZD_SPLIT='category' (default for NF-UNSW): the held-out attack is
    # time-clustered, so a purely temporal split leaves the test window with no
    # zero-day rows. We split KNOWN traffic chronologically but route the
    # held-out category's rows 50/50 (by their own time order) into val/test,
    # guaranteeing zero-day examples for calibration AND evaluation.
    # ZD_SPLIT='temporal' reproduces the original time-only split.
    ZD_SPLIT = os.environ.get('ZD_SPLIT', 'category')
    if ZD_SPLIT == 'category':
        tr_mask   = (ts < val_ts) & ~is_zd
        val_known = (ts >= val_ts) & (ts < test_ts) & ~is_zd
        te_known  = (ts >= test_ts) & ~is_zd
        zd_order  = np.where(is_zd)[0][np.argsort(ts[is_zd])]
        half      = len(zd_order) // 2
        zd_val = np.zeros(len(ts), dtype=bool); zd_val[zd_order[:half]] = True
        zd_te  = np.zeros(len(ts), dtype=bool); zd_te[zd_order[half:]]  = True
        val_mask = val_known | zd_val
        te_mask  = te_known  | zd_te
    else:
        tr_mask  = (ts < val_ts) & (lbl < num_known_cats)
        val_mask = (ts >= val_ts) & (ts < test_ts)
        te_mask  = ts >= test_ts

    train_data = Data(src[tr_mask], dst[tr_mask], ts[tr_mask], eidx[tr_mask], lbl[tr_mask])
    val_data   = Data(src[val_mask], dst[val_mask], ts[val_mask], eidx[val_mask], lbl[val_mask])
    test_data  = Data(src[te_mask],  dst[te_mask],  ts[te_mask],  eidx[te_mask],  lbl[te_mask])

    seen = set(train_data.sources) | set(train_data.destinations)
    nn_val_mask  = val_mask  & (~np.isin(src, list(seen)) | ~np.isin(dst, list(seen)))
    nn_test_mask = te_mask   & (~np.isin(src, list(seen)) | ~np.isin(dst, list(seen)))

    nn_val_data  = Data(src[nn_val_mask],  dst[nn_val_mask],  ts[nn_val_mask],
                        eidx[nn_val_mask],  lbl[nn_val_mask])
    nn_test_data = Data(src[nn_test_mask], dst[nn_test_mask], ts[nn_test_mask],
                        eidx[nn_test_mask], lbl[nn_test_mask])

    return (node_features, edge_features, full_data,
            train_data, val_data, test_data,
            nn_val_data, nn_test_data)


