def build_and_train_variant(agg='fourier', use_memory=True, motif=None,
                            lambda_proto=CFG['lambda_proto'],
                            n_harmonics=CFG['n_harmonics'],
                            n_layer=CFG['n_layer'], n_degree=CFG['n_degree'],
                            epochs=None, tag='variant', verbose=True):
    """Trains a fresh model with the given component/hyperparameter overrides,
    calibrates the zero-day detector on validation, evaluates on test, and
    returns a metrics dict. Mirrors the main training loop (chronological
    order, same three-term loss, validation-set link threshold)."""
    epochs = epochs or ABLATION_EPOCHS
    motif  = motif if motif is not None else motif_desc_train
    torch.manual_seed(42); np.random.seed(42)

    tr_nf = get_neighbor_finder(train_data, CFG['uniform'])
    fu_nf = get_neighbor_finder(full_data,  CFG['uniform'])

    m = TGNULTRAZeroDay(
        tr_nf, node_features, edge_features, DEVICE,
        n_layers=n_layer, n_heads=CFG['n_head'], dropout=CFG['dropout'],
        use_memory=use_memory, message_dimension=CFG['message_dim'],
        memory_dimension=CFG['memory_dim'],
        mean_time_shift_src=mts_src, std_time_shift_src=std_src,
        mean_time_shift_dst=mts_dst, std_time_shift_dst=std_dst,
        n_neighbors=n_degree, n_harmonics=n_harmonics,
        num_known_cats=NUM_KNOWN_CATS, ultra_hidden=CFG['ultra_hidden'],
        motif_dim=MotifDescriptor.MOTIF_DIM,
    ).to(DEVICE)

    # Aggregator ablation: swap Fourier → last-message
    if use_memory and agg == 'last':
        m.message_agg = get_message_aggregator('last', DEVICE, CFG['message_dim'])

    opt = torch.optim.AdamW(m.parameters(), lr=CFG['lr'], weight_decay=1e-5)
    sch = CosineAnnealingLR(opt, T_max=epochs, eta_min=1e-6)
    tr_s = RandEdgeSampler(train_data.sources, train_data.destinations)
    bce  = nn.BCELoss(); ce = nn.CrossEntropyLoss()

    for ep in range(epochs):
        m.train()
        if use_memory:
            m.memory.memory.data.fill_(0); m.memory.last_update.data.fill_(0)
            m.memory.messages = defaultdict(list); m.set_neighbor_finder(tr_nf)
        idx = np.arange(train_data.n_interactions)          # chronological
        for k in range(0, len(idx), CFG['bs']):
            bi = idx[k:k+CFG['bs']]
            s = train_data.sources[bi];     d  = train_data.destinations[bi]
            t = train_data.timestamps[bi];  ei = train_data.edge_idxs[bi]
            lb = train_data.labels[bi];     B  = len(s)
            _, ng = tr_s.sample(B)
            mp = motif.compute_batch(s, d, t, lb)
            mn = motif.compute_batch(s, ng, t, lb)
            opt.zero_grad()
            pp, npd, cl, jt, _ = m(s, d, ng, t, ei, mp, mn)
            l_link = bce(torch.cat([pp, npd]).clamp(1e-6, 1-1e-6),
                         torch.cat([torch.ones(B, device=DEVICE),
                                    torch.zeros(B, device=DEVICE)]))
            cats   = torch.tensor(lb, dtype=torch.long, device=DEVICE)
            l_cat  = ce(cl, cats)
            pn = F.normalize(m.ultra.prototypes.weight, dim=1)
            jn = F.normalize(jt, dim=1)
            l_proto = (1.0 - (jn * pn[cats]).sum(1)).mean()
            (l_link + CFG['lambda_cat']*l_cat + lambda_proto*l_proto).backward()
            torch.nn.utils.clip_grad_norm_(m.parameters(), 1.0)
            opt.step(); m.detach_memory()
        sch.step()

    # Calibrate zero-day detector on validation, evaluate on test
    if use_memory: m.set_neighbor_finder(fu_nf)
    vbk = m.memory_backup
    vr  = evaluate(m, motif, val_samp, val_data, n_degree, NUM_KNOWN_CATS)
    m.restore_memory(vbk)
    kn = ~vr['zd_true']
    with contextlib.redirect_stdout(io.StringIO()):       # silence calibration prints
        if kn.sum(): m.zd_detector.fit(vr['energies'][kn], vr['proto_dists'][kn])
        vood = m.zd_detector.score(vr['energies'], vr['proto_dists'])
        if vr['zd_true'].sum() > 0:
            m.zd_detector.calibrate_from_labels(vood, vr['zd_true'])

    tbk = m.memory_backup
    tr  = evaluate(m, motif, test_samp, test_data, n_degree, NUM_KNOWN_CATS,
                   link_threshold=vr['threshold'])
    m.restore_memory(tbk)
    ood = m.zd_detector.score(tr['energies'], tr['proto_dists'])
    zt  = tr['zd_true']; zp = ood > m.zd_detector.threshold
    zd_auc = roc_auc_score(zt.astype(int), ood) if (zt.any() and (~zt).any()) else 0.0
    zd_f1  = f1_score(zt.astype(int), zp.astype(int), zero_division=0)
    out = dict(link_ap=tr['ap'], link_auc=tr['auc'], cat_acc=tr['cat_acc'],
               hits10=tr['hits'][10], zd_f1=zd_f1, zd_auc=zd_auc)
    if verbose:
        print(f"[{tag:>16}] LinkAP={out['link_ap']:.3f}  CatAcc={out['cat_acc']:.3f}  "
              f"ZD-F1={zd_f1:.3f}  ZD-AUC={zd_auc:.3f}")
    return out, m, tr, vr
