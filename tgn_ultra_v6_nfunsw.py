# ---- 1. collect per-sample reps/logits/labels on val & test (no retrain) ----
def collect_reprs(model, motif, samp, data, n_nbr):
    samp.reset_random_state(); model.eval()
    J,Z,E,D,L = [],[],[],[],[]
    bk = model.memory_backup
    if CFG['use_memory']: model.set_neighbor_finder(full_nf)
    with torch.no_grad():
        N=len(data.sources)
        for k in range(math.ceil(N/CFG['bs'])):
            s=k*CFG['bs']; e=min(N,s+CFG['bs'])
            src=data.sources[s:e]; dst=data.destinations[s:e]; ts=data.timestamps[s:e]
            ei=data.edge_idxs[s:e]; lb=data.labels[s:e]; B=len(src)
            _,neg=samp.sample(B)
            mp=motif.compute_batch(src,dst,ts,lb); mn=motif.compute_batch(src,neg,ts,lb)
            _,_,cl,jt,_ = model(src,dst,neg,ts,ei,mp,mn,n_nbr)
            J.append(jt.cpu().numpy()); Z.append(cl.cpu().numpy())
            E.append(ZeroDayDetector.energy_score(cl))
            D.append(model.ultra.compute_prototype_distances(jt).cpu().numpy().min(1))
            L.append(np.asarray(lb))
    model.restore_memory(bk)
    L=np.concatenate(L)
    return dict(joint=np.concatenate(J), logits=np.concatenate(Z),
                energy=np.concatenate(E), proto=np.concatenate(D),
                labels=L, zd=(L==NUM_KNOWN_CATS))

