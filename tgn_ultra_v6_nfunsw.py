class ImprovedZeroDayDetector:
    """Mahalanobis-to-nearest-class-mean in joint space, combined with
    per-class-standardised energy; threshold calibrated at a fixed FPR."""
    def fit(self, joint, energy, labels, num_known, fpr_budget=0.01):
        self.mu = [];
        Xc = []
        for k in range(num_known):
            Xk = joint[labels==k]
            if len(Xk)<2: Xk = joint
            self.mu.append(Xk.mean(0)); Xc.append(Xk - Xk.mean(0))
        Xc = np.vstack(Xc)
        cov = np.cov(Xc.T) + 1e-3*np.eye(joint.shape[1])
        self.prec = np.linalg.pinv(cov)
        self.mu = np.stack(self.mu)
        # per-class energy standardisation stats
        self.e_mu = energy.mean(); self.e_sd = energy.std()+1e-9
        # calibrate threshold at fixed FPR on known (in-dist) val samples
        s = self.score(joint, energy)
        self.thr = np.quantile(s, 1-fpr_budget)
        return self
    def _maha(self, joint):
        d = joint[:,None,:]-self.mu[None,:,:]            # [N,K,H]
        m = np.einsum('nkh,hg,nkg->nk', d, self.prec, d) # squared distance
        return np.sqrt(m).min(1)
    def score(self, joint, energy):
        z_e = (energy-self.e_mu)/self.e_sd
        z_m = self._maha(joint)
        z_m = (z_m - z_m.mean())/(z_m.std()+1e-9)
        return 0.5*z_e + 0.5*z_m
    def predict(self, joint, energy): return self.score(joint,energy) > self.thr

