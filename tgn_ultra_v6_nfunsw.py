def precision_at_fpr(scores, y, val_scores, val_y, fpr_budget=0.01):
    """Threshold chosen on validation to hit a known-class FPR budget;
    report test precision/recall at that threshold."""
    fpr, tpr, thr = roc_curve(val_y.astype(int), val_scores)
    ok = fpr <= fpr_budget
    t = thr[np.where(ok)[0][-1]] if ok.any() else thr[0]
    pred = scores >= t
    tp = (pred & y).sum(); fp = (pred & ~y).sum(); fn = (~pred & y).sum()
    prec = tp/(tp+fp+1e-9); rec = tp/(tp+fn+1e-9)
    return float(prec), float(rec), float(t)

def precision_at_k(scores, y, k=None):
    k = k or int(y.sum())
    if k == 0: return 0.0
    idx = np.argsort(-scores)[:k]
    return float(y[idx].mean())

def zd_metric_block(val_e, val_d, te_e, te_d, val_zd, te_zd, alpha=0.5,
                    val_msp=None, te_msp=None, signal='combined'):
    """Compute zero-day metrics for a chosen OOD signal."""
    kn = ~val_zd
    def comb(e, d):
        em, es = val_e[kn].mean(), val_e[kn].std()+1e-9
        dm, ds = val_d[kn].mean(), val_d[kn].std()+1e-9
        return alpha*((e-em)/es) + (1-alpha)*((d-dm)/ds)
    if signal == 'energy':   vs, ts = val_e, te_e
    elif signal == 'proto':  vs, ts = val_d, te_d
    elif signal == 'msp':    vs, ts = val_msp, te_msp
    else:                    vs, ts = comb(val_e, val_d), comb(te_e, te_d)
    roc = roc_auc_score(te_zd.astype(int), ts) if (te_zd.any() and (~te_zd).any()) else 0.0
    pr  = average_precision_score(te_zd.astype(int), ts) if te_zd.any() else 0.0
    p1, r1, _ = precision_at_fpr(ts, te_zd, vs, val_zd, 0.01)
    pk = precision_at_k(ts, te_zd)
    # best-F1 (oracle) for reference
    P, R, _ = precision_recall_curve(te_zd.astype(int), ts)
    f1 = float(np.nanmax(2*P*R/(P+R+1e-9))) if te_zd.any() else 0.0
    return dict(roc_auc=roc, pr_auc=pr, prec_at_fpr1=p1, recall_at_fpr1=r1,
                prec_at_k=pk, best_f1=f1)

