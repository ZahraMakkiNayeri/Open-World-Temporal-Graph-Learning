"""## Section 8 – Graph Motif Descriptor (ULTRA-style Structural Encoder)

This is the key to Zero-Day generalisation. Instead of encoding an attack type by a learned ID embedding (which would be unknown for Zero-Day), we describe it by **how it behaves structurally** in the temporal graph:

| Motif Feature | DDoS | Port Scan | Normal |
|---|---|---|---|
| Fan-in (many→one) | High | Low | Medium |
| Fan-out (one→many) | Low | High | Low |
| Temporal burstiness | High | Medium | Low |
| Port diversity | Low | High | Low |
| Protocol entropy | Low | Low | High |

These motif vectors are computed *online* from the current batch's temporal neighbourhood — so even a brand-new attack type with unknown label still gets a meaningful structural description.

"""

class MotifDescriptor:
    """
    Computes a graph-structural (motif) feature vector for each interaction
    based on the temporal neighbourhood of source and destination nodes.

    Features (per interaction):
      0  : src fan-out (unique destinations in recent window)
      1  : dst fan-in  (unique sources in recent window)
      2  : temporal burstiness of src (coefficient of variation of inter-arrival times)
      3  : port diversity of interaction neighbourhood
      4  : protocol entropy of neighbourhood
      5  : ratio of repeat contacts (src→dst seen before)
      6  : recency score (how recently src was active)
      7  : dst concentration (how focused dst traffic is)
    """
    MOTIF_DIM = 8

    def __init__(self, graph_df, window_seconds=3600.0):
        """Pre-index the temporal graph for fast lookup."""
        self.window = window_seconds
        # Build index: src_node → sorted list of (ts, dst, port, proto)
        self.src_index = defaultdict(list)
        self.dst_index = defaultdict(list)
        for _, row in graph_df.iterrows():
            self.src_index[int(row.u)].append((row.ts, int(row.i), row.label))
            self.dst_index[int(row.i)].append((row.ts, int(row.u), row.label))
        # Sort by timestamp
        for k in self.src_index: self.src_index[k].sort()
        for k in self.dst_index: self.dst_index[k].sort()

    def _window_events(self, index, node, ts):
        """Return events in (ts-window, ts) for node."""
        evts = index.get(node, [])
        # Binary-search lower bound
        lo = 0; hi = len(evts)
        while lo < hi:
            mid=(lo+hi)//2
            if evts[mid][0] < ts - self.window: lo=mid+1
            else: hi=mid
        return [e for e in evts[lo:] if e[0] < ts]  # strictly before ts (no future leakage)

    def compute_batch(self, sources, destinations, timestamps, labels):
        """
        sources, destinations : numpy int arrays [B]
        timestamps            : numpy float array [B]
        labels                : numpy int array [B]
        Returns motif_matrix  : numpy float32 [B, MOTIF_DIM]
        """
        B   = len(sources)
        out = np.zeros((B, self.MOTIF_DIM), dtype=np.float32)

        for i in range(B):
            src = int(sources[i]); dst = int(destinations[i]); ts = float(timestamps[i])

            # Recent src activity
            src_evts = self._window_events(self.src_index, src, ts)
            dst_evts = self._window_events(self.dst_index, dst, ts)

            # 0: fan-out – unique destinations src contacted
            fanout = len(set(e[1] for e in src_evts)) if src_evts else 0

            # 1: fan-in – unique sources that contacted dst
            fanin  = len(set(e[1] for e in dst_evts)) if dst_evts else 0

            # 2: burstiness – coeff. of variation of src inter-arrival times
            if len(src_evts) >= 2:
                tss = np.array([e[0] for e in src_evts])
                iat = np.diff(tss)
                bursty = float(np.std(iat) / (np.mean(iat)+1e-9))
            else:
                bursty = 0.0

            # 3: port diversity (approximated via label entropy in neighbourhood)
            # (real port field not available after encoding, so we use label counts)
            lbl_src = [e[2] for e in src_evts]
            if lbl_src:
                vals, cnts = np.unique(lbl_src, return_counts=True)
                p = cnts / cnts.sum()
                port_div = float(-np.sum(p * np.log2(p+1e-9)))
            else:
                port_div = 0.0

            # 4: protocol entropy (same proxy)
            lbl_dst = [e[2] for e in dst_evts]
            if lbl_dst:
                vals, cnts = np.unique(lbl_dst, return_counts=True)
                p = cnts / cnts.sum()
                proto_ent = float(-np.sum(p * np.log2(p+1e-9)))
            else:
                proto_ent = 0.0

            # 5: repeat contact ratio
            prior_contacts = sum(1 for e in src_evts if e[1] == dst)
            repeat_ratio   = float(prior_contacts / (len(src_evts)+1e-9))

            # 6: recency score (1 / time since last src event)
            #if src_evts:
            #    recency = float(1.0 / (ts - src_evts[-1][0] + 1.0))
            #else:
            #    recency = 0.0

            # Source recency
            if src_evts:
                recency = float(1.0 / max(ts - src_evts[-1][0] + 1.0, 1e-9))
            else:
                recency = 0.0

            # Destination recency (check nearby lines for the same pattern)
            if dst_evts:
                dst_recency = float(1.0 / max(ts - dst_evts[-1][0] + 1.0, 1e-9))
            else:
                dst_recency = 0.0

            # 7: dst concentration (how much traffic dst gets vs src)
            dst_conc = float(fanin / (fanout + fanin + 1e-9))

            out[i] = [fanout, fanin, bursty, port_div, proto_ent,
                      repeat_ratio, recency, dst_conc]

        # Normalise each feature to [0,1] range within batch
        col_max = out.max(0) + 1e-9
        out = out / col_max
        return out


