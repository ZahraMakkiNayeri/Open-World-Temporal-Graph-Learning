    def _get_updated_memory(self, nodes, messages):
      ids, msgs, ts_agg = self._aggregate_messages(nodes, messages)
      if not ids:
        mem = self.memory.memory.data.clone()
        lu  = self.memory.last_update.data.clone()
        return mem, lu
        # msgs are already message_dim — no message_fn needed
      return self.memory_updater.get_updated_memory(ids, msgs, ts_agg)

    def _update_memory(self, nodes, messages):
        ids, msgs, ts_agg = self._aggregate_messages(nodes, messages)
        if not ids: return
        # msgs are already message_dim — no message_fn needed
        self.memory_updater.update_memory(ids, msgs, ts_agg)

    def _aggregate_messages(self, nodes, messages):
        node_ids = [n for n in np.unique(nodes) if n in messages and messages[n]]
        if not node_ids:
            return [], torch.empty(0,device=self.device), torch.empty(0,device=self.device)
        ids, msgs, ts_agg = self.message_agg.aggregate(node_ids, messages)
        if not ids:
            return [], torch.empty(0,device=self.device), torch.empty(0,device=self.device)
        return ids, msgs, ts_agg

    def _get_raw_messages(self, src, src_e, dst, dst_e, ts, eidx):
        ts_t  = torch.FloatTensor(ts).to(self.device)
        ef    = self.edge_raw[eidx,:]
        sm    = self.memory.get_memory(src); dm = self.memory.get_memory(dst)
        s_lu  = self.memory.last_update[src]; d_lu = self.memory.last_update[dst]
        s_td  = self.time_encoder((ts_t-s_lu).unsqueeze(-1)).squeeze(-2)
        d_td  = self.time_encoder((ts_t-d_lu).unsqueeze(-1)).squeeze(-2)
        rm_s  = torch.cat([sm,dm,ef,s_td],1); rm_d = torch.cat([dm,sm,ef,d_td],1)
        r_src = {n:[(rm_s[i],ts_t[i])] for i,n in enumerate(src)}
        r_dst = {n:[(rm_d[i],ts_t[i])] for i,n in enumerate(dst)}
        return r_src, r_dst

