class MotifZero:
    """All-zero motif vectors → ablate the structural signal entirely."""
    MOTIF_DIM = MotifDescriptor.MOTIF_DIM
    def __init__(self, base): self.base = base
    def compute_batch(self, s, d, t, l):
        return np.zeros((len(s), self.MOTIF_DIM), dtype=np.float32)

class MotifDrop:
    """Zero a single motif feature → leave-one-out."""
    def __init__(self, base, drop_idx): self.base = base; self.drop = drop_idx
    def compute_batch(self, s, d, t, l):
        m = self.base.compute_batch(s, d, t, l).copy()
        m[:, self.drop] = 0.0
        return m

