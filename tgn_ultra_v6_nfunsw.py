"""## Section 9 – ULTRA Structural Relation Encoder

The key insight from ULTRA: **encode a relation (attack type) by its structural role in the graph, not by its ID**.

Here we implement this as:
1. Input = **motif descriptor** (8-dim structural signature) of the interaction
2. Two-stream encoder: **node embedding stream** (from TGN) + **motif stream**
3. Cross-attention between streams → joint representation
4. This joint representation can score *any* link, including unseen attack types,
   because it operates on *structural patterns*, not on categorical IDs.

"""

class ULTRAStructuralRelationEncoder(nn.Module):
    """
    ULTRA-style relation encoder that operates on graph motif descriptors
    rather than relation ID embeddings.

    For KNOWN attack types: uses motif + learned prototype alignment.
    For UNKNOWN (Zero-Day): produces an embedding purely from motif structure
                            → enables open-world link scoring.

    Architecture:
        motif_vec [B,8] ──► motif_proj [B,D]  ─┐
                                                 ├── CrossAttn ──► joint [B,D] ──► link_score
        [src║dst] [B,2D] ──► node_proj [B,D]  ─┘
    """
    def __init__(self, node_dim, motif_dim=8, hidden_dim=256,
                 num_known_relations=4, dropout=0.1):
        super().__init__()
        self.node_dim   = node_dim
        self.hidden_dim = hidden_dim
        self.num_known  = num_known_relations

        # Motif stream
        self.motif_proj = nn.Sequential(
            nn.Linear(motif_dim, hidden_dim), nn.LayerNorm(hidden_dim), nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(hidden_dim, hidden_dim))

        # Node stream
        self.node_proj = nn.Sequential(
            nn.Linear(2*node_dim, hidden_dim), nn.LayerNorm(hidden_dim), nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(hidden_dim, hidden_dim))

        # Cross-attention (node queries, motif keys/values)
        self.cross_attn = nn.MultiheadAttention(
            embed_dim=hidden_dim, num_heads=4, dropout=dropout, batch_first=True)

        # Learned class prototypes (for known relations only)
        self.prototypes = nn.Embedding(num_known_relations, hidden_dim)
        nn.init.xavier_normal_(self.prototypes.weight)

        # Final scorer
        self.scorer = nn.Sequential(
            nn.Linear(hidden_dim, hidden_dim//2), nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(hidden_dim//2, 1))

        # Category classifier (for known classes + open-set detection)
        self.classifier = nn.Linear(hidden_dim, num_known_relations)

        self._init_weights()

    def _init_weights(self):
        for m in self.modules():
            if isinstance(m, nn.Linear):
                nn.init.xavier_normal_(m.weight)
                if m.bias is not None: nn.init.zeros_(m.bias)

    def encode(self, src_emb, dst_emb, motif_vec):
        """
        Returns joint representation [B, hidden_dim].
        Works for ANY interaction, including zero-day.
        """
        node_in  = torch.cat([src_emb, dst_emb], dim=1)       # [B, 2D]
        node_h   = self.node_proj(node_in)                     # [B, H]
        motif_h  = self.motif_proj(motif_vec)                  # [B, H]

        # Two-token sequence (node + motif) so BOTH streams influence the
        # fused representation. With a single key/value the attention weight
        # collapses to 1.0 and the node embedding is discarded; attending over
        # a 2-token sequence keeps the TGN node/temporal info in the joint repr.
        seq         = torch.stack([node_h, motif_h], dim=1)    # [B, 2, H]
        attn_out, _ = self.cross_attn(seq, seq, seq)           # [B, 2, H]
        joint       = attn_out.mean(dim=1)                     # [B, H] (node+motif)
        return joint

    def forward(self, src_emb, dst_emb, motif_vec):
        """
        Returns:
            link_score  [B]  – link existence probability (pre-sigmoid)
            cat_logits  [B, num_known]  – class logits (for known attack types)
            joint_repr  [B, hidden_dim] – for OOD scoring
        """
        joint      = self.encode(src_emb, dst_emb, motif_vec)
        link_score = self.scorer(joint).squeeze(-1)
        cat_logits = self.classifier(joint)
        return link_score, cat_logits, joint

    def compute_prototype_distances(self, joint_repr):
        """
        Cosine distance from each class prototype.
        Used for Zero-Day detection: large min-distance → unseen class.
        Returns dist [B, num_known]
        """
        proto = self.prototypes.weight  # [K, H]
        j_n   = F.normalize(joint_repr, dim=1)  # [B, H]
        p_n   = F.normalize(proto, dim=1)        # [K, H]
        sim   = j_n @ p_n.T                      # [B, K]
        return 1.0 - sim                          # cosine distance ∈ [0,2]

print("ULTRA Structural Relation Encoder defined ✓")

"""## Section 10 – Zero-Day OOD Detector

Two complementary OOD signals are combined:

1. **Energy score** — $E(\mathbf{h}) = -\log\sum_k \exp(\text{logit}_k)$ — low energy = in-distribution, high energy = out-of-distribution
2. **Prototype distance** — cosine distance to nearest known-class prototype — large = structurally unlike any known attack

Combined score: $S_{\text{OOD}} = \alpha \cdot E_{\text{norm}} + (1-\alpha) \cdot d_{\min}$

Threshold calibrated on validation set Zero-Day samples.

"""

class ZeroDayDetector:
    """
    Post-hoc Zero-Day detector that combines:
      - Energy-based OOD score (from classifier logits)
      - Prototype distance score (from ULTRA structural encoder)

    Usage:
      1. fit(known_energies, known_dists)   – calibrate thresholds on val set
      2. score(logits, dists)               – compute OOD score for new samples
      3. predict(scores)                    – binary Zero-Day prediction
    """
    def __init__(self, alpha=0.5):
        self.alpha     = alpha
        self.threshold = None
        self.e_mean    = 0.0; self.e_std = 1.0
        self.d_mean    = 0.0; self.d_std = 1.0

    # ── Energy score ─────────────────────────────────────────
    @staticmethod
    def energy_score(logits):
        """logits: [B, K] tensor → energy [B] (numpy)"""
        with torch.no_grad():
            E = -torch.logsumexp(logits, dim=1).cpu().numpy()
        return E   # more positive = more OOD

    # ── Min prototype distance ────────────────────────────────
    @staticmethod
    def min_proto_dist(dist_matrix):
        """dist_matrix: [B, K] numpy → min_dist [B]"""
        return dist_matrix.min(axis=1)

    # ── Fit calibration ───────────────────────────────────────
    def fit(self, known_energies, known_dists):
        """
        known_energies, known_dists: numpy arrays from IN-DISTRIBUTION val samples.
        We set threshold at mean + 2*std of combined OOD score.
        """
        self.e_mean = known_energies.mean(); self.e_std = known_energies.std()+1e-9
        self.d_mean = known_dists.mean();    self.d_std = known_dists.std()+1e-9
        e_norm = (known_energies - self.e_mean) / self.e_std
        d_norm = (known_dists    - self.d_mean) / self.d_std
        scores = self.alpha * e_norm + (1-self.alpha) * d_norm
        self.threshold = scores.mean() + 2.0 * scores.std()
        print(f"  ZeroDay threshold calibrated: {self.threshold:.4f}  "
              f"(mean={scores.mean():.4f}, std={scores.std():.4f})")
        return self

    # ── Compute OOD score ─────────────────────────────────────
    def score(self, energies, dists):
        e_norm = (energies - self.e_mean) / self.e_std
        d_norm = (dists    - self.d_mean) / self.d_std
        return self.alpha * e_norm + (1-self.alpha) * d_norm

    # ── Predict ───────────────────────────────────────────────
    def predict(self, scores):
        """Returns bool array: True = Zero-Day"""
        assert self.threshold is not None, 'Call fit() first'
        return scores > self.threshold

    # ── Find best threshold on labelled val set ───────────────
    def calibrate_from_labels(self, scores, true_zeroday_mask):
        """
        Scan thresholds to maximise F1 on Zero-Day detection.
        true_zeroday_mask: bool numpy array
        """
        best_f1, best_t = 0.0, 0.0
        for t in np.linspace(scores.min(), scores.max(), 200):
            pred = (scores > t).astype(int)
            f1   = f1_score(true_zeroday_mask.astype(int), pred, zero_division=0)
            if f1 > best_f1: best_f1, best_t = f1, t
        self.threshold = best_t
        print(f"  Best Zero-Day threshold: {best_t:.4f}  (F1={best_f1:.4f})")
        return best_f1

