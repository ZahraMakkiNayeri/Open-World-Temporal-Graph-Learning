    opt = torch.optim.AdamW(m.parameters(), lr=CFG['lr'], weight_decay=1e-5)
    sch = CosineAnnealingLR(opt, T_max=epochs, eta_min=1e-6)
    tr_s = RandEdgeSampler(tr.sources, tr.destinations, seed=seed)
    vl_s = RandEdgeSampler(fd.sources, fd.destinations, seed=seed+10)
